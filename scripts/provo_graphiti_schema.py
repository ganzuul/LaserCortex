# Cypher for creating the schema in Graphiti (FalkorDB)
# ═══════════════════════════════════════════════════════════════════════

def build_schema_cypher() -> List[str]:
    """Build Cypher statements to create the PROV-O schema in Graphiti.

    Each CSG category becomes a node with:
    - prov: label (the PROV-O class)
    - csg_category: the category name
    - tree_shape, vsm, cd_step, friction_cost: our properties
    - anchors: the verbose anchor texts

    PROV-O properties become edge types:
    - (:Plan)-[:PRODUCES]->(:Activity)  (temporalMonad → computationAction)
    - (:Activity)-[:USED]->(:Entity)     (computationAction → exploration)
    - (:Activity)-[:HAD_ROLE]->(:Role)   (computationAction → scope)
    - (:Entity)-[:WAS_ATTRIBUTED_TO]->(:Agent)  (exploration → idempotentTarget)
    - (:Entity)-[:WAS_DERIVED_FROM]->(:Derivation)  (exploration → certifiedGeometry)
    """
    statements = []

    # Create category nodes
    for cat_name, info in CATEGORY_TO_PROVO.items():
        provo_class = info["provo_class"]
        gamma = friction_density(info["cd_step"])
        anchors_json = json.dumps(info["anchors"])
        # Escape single quotes in anchors
        anchors_escaped = anchors_json.replace("'", "\\'")

        stmt = (
            f"MERGE (c:{provo_class}:CSGCategory "
            f"{{name: '{cat_name}', provo_class: '{provo_class}', "
            f"provo_uri: '{info['provo_uri']}', "
            f"tree_shape: '{info['tree_shape']}', "
            f"vsm: '{info['vsm']}', "
            f"cd_step: {info['cd_step']}, "
            f"friction_cost: {gamma}, "
            f"provo_doc: '{info['provo_doc'][:200]}'}}) "
            f"SET c.anchors = '{anchors_escaped}'"
        )
        statements.append(stmt)

    # Create VSM system nodes
    for vsm, (prop_name, prop_uri, doc) in VSM_TO_PROVO.items():
        stmt = (
            f"MERGE (v:VSMSystem {{name: '{vsm}', "
            f"provo_property: '{prop_name}', "
            f"provo_uri: '{prop_uri}', "
            f"doc: '{doc}'}})"
        )
        statements.append(stmt)

    # Create edges: category → VSM system (which VSM system governs this category)
    for cat_name, info in CATEGORY_TO_PROVO.items():
        vsm = info["vsm"]
        stmt = (
            f"MATCH (c:CSGCategory {{name: '{cat_name}'}}), "
            f"(v:VSMSystem {{name: '{vsm}'}}) "
            f"MERGE (c)-[:GOVERNED_BY]->(v)"
        )
        statements.append(stmt)

    # Create edges: category → category (the CFG production chain)
    # temporalMonad → computationAction → (scope, exploration) → certifiedGeometry
    # → idempotentTarget
    chain = [
        ("temporalMonad", "computationAction", "PRODUCES"),
        ("computationAction", "scope", "HAS_ROLE"),
        ("computationAction", "exploration", "USED"),
        ("exploration", "certifiedGeometry", "WAS_DERIVED_FROM"),
        ("exploration", "idempotentTarget", "WAS_ATTRIBUTED_TO"),
    ]
    for src, tgt, edge_type in chain:
        stmt = (
            f"MATCH (s:CSGCategory {{name: '{src}'}}), "
            f"(t:CSGCategory {{name: '{tgt}'}}) "
            f"MERGE (s)-[:{edge_type}]->(t)"
        )
        statements.append(stmt)

    return statements


def build_anchor_episodes() -> List[Dict[str, str]]:
    """Build episode data for each anchor text.

    Each anchor becomes an episode in the Graphiti graph, linked to its
    category via the episode body. The embedding server can then compute
    cosine similarities between phrases and these anchor episodes.
    """
    episodes = []
    for cat_name, info in CATEGORY_TO_PROVO.items():
        for i, anchor in enumerate(info["anchors"]):
            episodes.append({
                "name": f"{cat_name}_anchor_{i}",
                "body": anchor,
                "group_id": "provo_schema",
                "source_description": f"prov:{info['provo_class']} anchor for {cat_name}",
                "category": cat_name,
                "provo_class": info["provo_class"],
                "tree_shape": info["tree_shape"],
                "cd_step": info["cd_step"],
            })
    return episodes


async def main():
    print("=" * 70)
    print("PROV-O → Graphiti Schema Ingestion")
    print("=" * 70)

    # Print the mapping
    print("\n─ CSG Category → PROV-O Class mapping ─")
    for cat_name, info in CATEGORY_TO_PROVO.items():
        gamma = friction_density(info["cd_step"])
        print(f"  {cat_name:22s} → prov:{info['provo_class']:15s} "
              f"  {info['tree_shape']:45s}  Γ={gamma:.0f}  {info['vsm']}")

    print("\n─ VSM System → PROV-O Property mapping ─")
    for vsm, (prop, uri, doc) in VSM_TO_PROVO.items():
        print(f"  {vsm:4s} → prov:{prop:20s}  {doc}")

    # Build and execute schema
    print("\n─ Creating schema in Graphiti (FalkorDB) ─")
    service = GraphitiService(db_path="data/provo_glossary.db")

    try:
        await service.start()
        print("  GraphitiService started")

        # Execute schema Cypher
        statements = build_schema_cypher()
        driver = service.driver

        for stmt in statements:
            try:
                await driver.execute_query(stmt)
            except Exception as e:
                print(f"  [SKIP] {stmt[:80]}... — {e}")

        print(f"  Created {len(statements)} schema statements")

        # Verify: count nodes
        result = await driver.execute_query(
            "MATCH (n) RETURN labels(n) as labels, count(n) as count"
        )
        print("\n─ Node count by label ─")
        if result and result[0]:
            for record in result[0]:
                labels = record.get("labels", [])
                count = record.get("count", 0)
                print(f"  {':'.join(labels):40s} {count}")

        # Verify: count edges
        result = await driver.execute_query(
            "MATCH ()-[r]->() RETURN type(r) as type, count(r) as count"
        )
        print("\n─ Edge count by type ─")
        if result and result[0]:
            for record in result[0]:
                edge_type = record.get("type", "")
                count = record.get("count", 0)
                print(f"  {edge_type:40s} {count}")

        # Ingest anchor texts as episodes
        print("\n─ Ingesting anchor texts as episodes ─")
        episodes = build_anchor_episodes()
        for ep in episodes:
            await service.add_episode(
                name=ep["name"],
                body=ep["body"],
                group_id=ep["group_id"],
                source_description=ep["source_description"],
            )
        print(f"  Ingested {len(episodes)} anchor episodes")

        # Show the full glossary graph
        print("\n─ Full glossary graph ─")
        result = await driver.execute_query(
            "MATCH (c:CSGCategory)-[r]->(t) "
            "RETURN c.name as source, type(r) as edge, t.name as target "
            "ORDER BY c.name"
        )
        if result and result[0]:
            for record in result[0]:
                src = record.get("source", "")
                edge = record.get("edge", "")
                tgt = record.get("target", "")
                print(f"  {src:22s} -[:{edge:20s}]-> {tgt}")

        print("\n" + "=" * 70)
        print("Schema ingestion complete.")
        print("The glossary is now a typed PROV-O graph in Graphiti.")
        print("Each CSG category is a prov: class node with its EMLTree shape")
        print("and friction cost. Anchor texts are episodes for embedding.")
        print("=" * 70)

    finally:
        await service.stop()


if __name__ == "__main__":
    asyncio.run(main())
