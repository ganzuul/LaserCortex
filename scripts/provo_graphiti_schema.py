STRUT_WEIGHT = 4
BARRIER = STRUT_WEIGHT * STRUT_WEIGHT


def friction_density(cd_step: int) -> float:
    assoc = 0 if cd_step <= 2 else STRUT_WEIGHT
    return float(cd_step + STRUT_WEIGHT * assoc)


