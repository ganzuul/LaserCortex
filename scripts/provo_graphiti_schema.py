#!/usr/bin/env python3
"""PROV-O → Graphiti schema: ingest the W3C provenance ontology as the
typed schema for the CSG → CFG lifting glossary.

Instead of ad-hoc string constants, the glossary is a property graph
whose node labels and edge types come from the W3C PROV-O recommendation
(https://www.w3.org/TR/prov-o/). This gives us:

- Formal semantics (OWL classes and properties)
- Documentation (W3C Recommendation with 10+ years of community use)
- Interoperability (standard provenance model)

The 6 CSG grammar categories map to PROV-O classes:

  temporalMonad      → prov:Plan        (intended set of actions)
  computationAction  → prov:Activity     (action acting on entities)
  scope              → prov:Role         (constraint on the activity)
  exploration        → prov:Entity       (thing being explored/used)
  idempotentTarget   → prov:Agent        (bears responsibility/commitment)
  certifiedGeometry  → prov:Derivation   (certified derivation chain)

The VSM loop maps to PROV-O properties:

  S1 (Operations)    → prov:used            (Activity used Entity)
  S2 (Coordination)  → prov:wasInformedBy   (Activity informed by Activity)
  S3 (Regulation)    → prov:wasGeneratedBy  (Entity generated by Activity)
  S3* (Audit)        → prov:wasDerivedFrom  (Entity derived from Entity)
  S4 (Generation)    → prov:hadPlan         (Association had Plan)
  S5 (Identity)      → prov:wasAttributedTo (Entity attributed to Agent)

Usage:
    python3 scripts/provo_graphiti_schema.py

This creates the schema in the Graphiti graph and stores the 6 categories
as prov:Plan, prov:Activity, prov:Role, prov:Entity, prov:Agent, and
prov:Derivation nodes with their EMLTree shapes and friction costs.
"""
