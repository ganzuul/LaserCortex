SCOPING_WORDS = {
    "only", "specific", "precisely", "exactly", "target", "focused",
    "limited", "narrow", "particular", "single", "just", "first",
    "before", "critical", "most",
}

CERTAINTY_WORDS = {
    "definitely", "certainly", "confident", "must", "exactly", "really",
    "certainly", "sure", "right", "correct", "complete", "holds",
    "cannot", "without",
}


def extract_words(text: str) -> List[str]:
    """Extract lowercased words from text."""
    return re.findall(r"[a-zA-Z]+", text.lower())


def analyze_text(text: str) -> Dict[str, Any]:
    """Crude linguistic analysis of a text."""
    words = extract_words(text)
    word_set = set(words)

    # Detect scoping language
    scoping = word_set & SCOPING_WORDS
    # Detect certainty language
    certainty = word_set & CERTAINTY_WORDS
    # Detect action verbs (imperative or gerund)
    action_verbs = word_set & {
        "run", "execute", "parse", "search", "lift", "ground", "build",
        "compute", "produce", "check", "verify", "generate", "transform",
        "modify", "consume", "process", "relocate", "use", "create",
        "construct", "update", "derive", "complete",
    }
    # Detect cognitive verbs
    cognitive_verbs = word_set & {
        "understand", "explore", "investigate", "examine", "study", "look",
        "figure", "know", "think",
    }
    # Detect intent language
    intent_markers = word_set & {
        "let", "should", "need", "will", "must", "intend", "want",
        "begin", "start", "first", "before",
    }
    # Detect first person
    first_person = word_set & {"i", "me", "my", "we", "us", "our"}
    # Detect passive voice markers
    passive = word_set & {"was", "were", "been", "being", "is", "are"}

    # Sentence starts with imperative verb?
    first_word = words[0].lower() if words else ""
    starts_imperative = first_word in action_verbs

    return {
        "word_count": len(words),
        "scoping_words": sorted(scoping),
        "certainty_words": sorted(certainty),
        "action_verbs": sorted(action_verbs),
        "cognitive_verbs": sorted(cognitive_verbs),
        "intent_markers": sorted(intent_markers),
        "first_person": bool(first_person),
        "starts_imperative": starts_imperative,
        "has_passive": bool(passive),
    }


