"""Analyse the linguistic bridge between the bge-m3 embedding space and the
PROV-O OWL ontology.

The question: when we assign a phrase to a CSG category via embedding cosine
similarity to anchor texts, does the result actually align with what PROV-O
*means* by the corresponding class? Or is the embedding capturing surface
features that don't correspond to the ontology's formal semantics?

Method:
  1. Extract ALL PROV-O class/property definitions from the OWL file.
  2. Embed the PROV-O definitions + our anchor texts + a sample of trace
     phrases.
  3. Compute three matrices:
     a) Our 6 categories (anchor centroid) × 6 mapped PROV-O classes
     b) Our 6 categories (anchor centroid) × ALL PROV-O classes (find nearest)
     c) Sample trace phrases × our 6 categories × PROV-O classes
  4. Linguistic analysis: extract verbs, nouns, sentence patterns from both
     PROV-O definitions and anchor texts. Compare POS distributions.
  5. Report mismatches and corrected mappings.

Usage:
    python3 scripts/analyse_provo_embedding.py
"""
