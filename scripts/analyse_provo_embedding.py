# 3. Embedding helpers
# ═══════════════════════════════════════════════════════════════════════

EMBED_URL = "http://localhost:8082/v1/embeddings"


def embed_texts(texts: List[str], batch_size: int = 2) -> List[List[float]]:
    """Embed texts via bge-m3 on :8082. Batch size 2 per SAFETY.md INC-1."""
    all_embeddings = []
    for i in range(0, len(texts), batch_size):
        batch = texts[i:i + batch_size]
        payload = json.dumps({"input": batch, "max_length": 500}).encode()
        req = urllib.request.Request(
            EMBED_URL,
            data=payload,
            headers={"Content-Type": "application/json"},
        )
        for attempt in range(3):
            try:
                with urllib.request.urlopen(req, timeout=30) as resp:
                    data = json.loads(resp.read())
                all_embeddings.extend(data["data"][j]["embedding"] for j in range(len(batch)))
                break
            except Exception as e:
                if attempt < 2:
                    time.sleep(1)
                else:
                    print(f"  [ERROR] embed batch {i}: {e}")
                    all_embeddings.extend([[0.0] * 1024] * len(batch))
    return all_embeddings


def cosine_sim(a: List[float], b: List[float]) -> float:
    dot = sum(x * y for x, y in zip(a, b))
    na = sum(x * x for x in a) ** 0.5
    nb = sum(y * y for y in b) ** 0.5
    if na == 0 or nb == 0:
        return 0.0
    return dot / (na * nb)


def centroid(embeddings: List[List[float]]) -> List[float]:
    n = len(embeddings)
    if n == 0:
        return [0.0] * 1024
    return [sum(e[i] for e in embeddings) / n for i in range(1024)]


